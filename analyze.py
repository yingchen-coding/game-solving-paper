"""Cross-condition analysis for CONCLUSIONS.md: pre-registered comparisons with exact tests, and the evidence mechanism.

Usage: analyze.py  (reads runs/<cond>/episodes.jsonl, runs diagnose.py where diagnosis.json is missing or stale)
"""
import json
import math
import random
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

import diagnose
import envs

RUNS = Path("runs")
CONDS = {  # label: run dir. All Qwen2.5-7B-Instruct 4-bit, eval seeds 10000-10019, 20 per env.
    "plain": "q7_plain", "strategy prompt": "q7_strategy", "self-written playbook": "q7_playbook",
    "expert rules playbook": "h8_expert", "fine-tune on own wins": "q7_ei_r1", "own wins + playbook": "q7_ei_playbook",
    "fine-tune on worked examples": "stick_worked", "CHECK tool (untrained)": "q7_checktool",
    "encourage": "moment_encourage", "yell": "moment_yell", "remind": "moment_remind", "hint": "moment_hint",
    "coach": "moment_coach",
}
TRAIN = [c.name for c in envs.TRAIN_GAMES]
HELD = [c.name for c in envs.HELD_OUT]


def load(run):
    path = RUNS / run / "episodes.jsonl"
    if not path.exists():
        return None
    eps = [json.loads(x) for x in path.open()]
    return eps if len(eps) >= 120 else None


def diagnosis(run):
    d = RUNS / run / "diagnosis.json"
    eps = RUNS / run / "episodes.jsonl"
    if not d.exists() or d.stat().st_mtime < eps.stat().st_mtime:
        subprocess.run([sys.executable, "diagnose.py", str(RUNS / run)], check=True, capture_output=True)
    return json.loads(d.read_text())


def fisher_two_sided(a, n1, b, n2):
    """Exact two-sided Fisher test for a/n1 vs b/n2 successes."""
    k, n = a + b, n1 + n2
    def p(x):
        return math.comb(n1, x) * math.comb(n2, k - x) / math.comb(n, k)
    obs = p(a)
    return min(1.0, sum(p(x) for x in range(max(0, k - n2), min(k, n1) + 1) if p(x) <= obs * (1 + 1e-9)))


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for r, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - r) * ps[i]))
        adj[i] = run
    return adj


def spearman(x, y):
    def ranks(v):
        o = sorted(range(len(v)), key=lambda i: v[i])
        r = [0.0] * len(v)
        i = 0
        while i < len(o):
            j = i
            while j + 1 < len(o) and v[o[j + 1]] == v[o[i]]:
                j += 1
            for t in range(i, j + 1):
                r[o[t]] = (i + j) / 2
            i = j + 1
        return r
    rx, ry = ranks(x), ranks(y)
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    den = math.sqrt(sum((a - mx) ** 2 for a in rx) * sum((b - my) ** 2 for b in ry))
    return num / den if den else float("nan")


def boot_ci(xs, ys, reps=4000, seed=0):
    rng = random.Random(seed)
    diffs = sorted(sum(rng.choices(xs, k=len(xs))) / len(xs) - sum(rng.choices(ys, k=len(ys))) / len(ys)
                   for _ in range(reps))
    return diffs[int(0.025 * reps)], diffs[int(0.975 * reps)]


def main():
    data = {lab: load(run) for lab, run in CONDS.items()}
    data = {k: v for k, v in data.items() if v}
    succ = {lab: defaultdict(list) for lab in data}
    for lab, eps in data.items():
        for e in eps:
            succ[lab][e["env"]].append(int(bool(e["success"])))
    diag = {lab: diagnosis(CONDS[lab]) for lab in data}
    out = ["# Analysis (generated by analyze.py — do not edit by hand)", "",
           "Qwen2.5-7B-Instruct 4-bit, 20 problems per task per condition (eval seeds 10000-10019, never trained on).", ""]

    out += ["## 1. Success by condition", "",
            "| Condition | " + " | ".join(TRAIN + HELD) + " | practised (/80) | never practised (/40) |",
            "|---|" + "---|" * (len(TRAIN + HELD) + 2)]
    for lab in data:
        s = succ[lab]
        tr, he = sum(sum(s[e]) for e in TRAIN), sum(sum(s[e]) for e in HELD)
        out.append(f"| {lab} | " + " | ".join(str(sum(s[e])) for e in TRAIN + HELD) + f" | {tr} | {he} |")

    tests = [  # (claim, condition, envs) — chosen from the hypotheses before looking at significance
        ("fine-tuning on own wins raises practised games", "fine-tune on own wins", TRAIN),
        ("own wins + playbook raises practised games", "own wins + playbook", TRAIN),
        ("worked examples raise practised games", "fine-tune on worked examples", TRAIN),
        ("strategy prompt raises never-practised", "strategy prompt", HELD),
        ("fine-tuning on own wins raises never-practised", "fine-tune on own wins", HELD),
        ("worked examples raise never-practised", "fine-tune on worked examples", HELD),
        ("yell changes practised games", "yell", TRAIN),
        ("encourage changes practised games", "encourage", TRAIN),
        ("coach changes practised games", "coach", TRAIN),
        ("untrained CHECK tool changes practised games", "CHECK tool (untrained)", TRAIN),
    ]
    tests = [t for t in tests if t[1] in data]
    rows, ps = [], []
    for claim, lab, es in tests:
        a = [x for e in es for x in succ[lab][e]]
        b = [x for e in es for x in succ["plain"][e]]
        p = fisher_two_sided(sum(a), len(a), sum(b), len(b))
        lo, hi = boot_ci(a, b)
        rows.append((claim, lab, sum(a), len(a), sum(b), len(b), sum(a) / len(a) - sum(b) / len(b), lo, hi, p))
        ps.append(p)
    adj = holm(ps)
    out += ["", "## 2. Pre-chosen comparisons vs plain (Fisher exact, Holm-corrected over these tests)", "",
            "| Claim | Condition | Plain | Δ | 95% CI | p | p (Holm) |", "|---|---|---|---|---|---|---|"]
    for (claim, lab, a, na, b, nb, d, lo, hi, p), pa in zip(rows, adj):
        out.append(f"| {claim} | {a}/{na} | {b}/{nb} | {d:+.2f} | [{lo:+.2f}, {hi:+.2f}] | {p:.3f} | {pa:.3f} |")

    per_env = []
    out += ["", "## 3. Per-task effects with p < 0.05 (uncorrected; exploratory)", "",
            "| Condition | Task | Condition | Plain | p |", "|---|---|---|---|---|"]
    for lab in data:
        if lab == "plain":
            continue
        for e in TRAIN + HELD:
            a, b = succ[lab][e], succ["plain"][e]
            p = fisher_two_sided(sum(a), len(a), sum(b), len(b))
            if p < 0.05:
                per_env.append((lab, e, sum(a), sum(b), p))
                out.append(f"| {lab} | {e} | {sum(a)}/{len(a)} | {sum(b)}/{len(b)} | {p:.3f} |")

    out += ["", "## 4. Mechanism: acting against evidence the model already has", "",
            "Episode level, pooled over all conditions: success rate when the episode contains at least one action that",
            "contradicts earlier feedback, vs when it contains none (diagnose.py).", "",
            "| Task | with contradiction | without | p |", "|---|---|---|---|"]
    for e in TRAIN + HELD:
        with_c = [0, 0]
        without = [0, 0]
        for lab, eps in data.items():
            for ep in eps:
                if ep["env"] != e:
                    continue
                tgt = with_c if "contradicts" in diagnose.classify(ep) else without
                tgt[0] += int(bool(ep["success"]))
                tgt[1] += 1
        if with_c[1] and without[1]:
            p = fisher_two_sided(with_c[0], with_c[1], without[0], without[1])
            out.append(f"| {e} | {with_c[0]}/{with_c[1]} ({with_c[0] / with_c[1]:.0%}) | "
                       f"{without[0]}/{without[1]} ({without[0] / without[1]:.0%}) | {p:.2g} |")

    out += ["", "Condition level: Spearman correlation, across conditions, between a task's contradiction rate and its",
            "success rate (each point = one condition).", "", "| Task | ρ | conditions |", "|---|---|---|"]
    for e in TRAIN + HELD:
        xs, ys = [], []
        for lab in data:
            c = diag[lab].get(e, {})
            if "contradicts" in c or c.get("actions"):
                xs.append(c.get("contradicts", 0.0))
                ys.append(c.get("success", 0) / max(1, c.get("episodes", 20)))
        if len(set(xs)) > 1 and len(set(ys)) > 1:
            out.append(f"| {e} | {spearman(xs, ys):+.2f} | {len(xs)} |")

    controls = [c for c in ("encourage", "remind", "hint") if c in data]
    guidance = [c for c in ("strategy prompt", "expert rules playbook") if c in data]
    out += ["", "## 5. Guidance helps where the model is a novice and hurts where it is already good",
            "(expertise-reversal test). Same seeds and greedy decoding everywhere, so any prompt change perturbs",
            "outcomes; the control is the pooled light-touch conditions (" + ", ".join(controls) + "), which add",
            "text without telling the model how to work.", "",
            "| Task (plain success) | " + " | ".join(guidance) + " | controls pooled | p each vs controls |",
            "|---|" + "---|" * (len(guidance) + 2)]
    for e in ("oddcoin", "hiddenrule"):
        cs = [x for c in controls for x in succ[c][e]]
        cells, pv = [], []
        for g in guidance:
            a = succ[g][e]
            cells.append(f"{sum(a)}/{len(a)}")
            pv.append(f"{fisher_two_sided(sum(a), len(a), sum(cs), len(cs)):.3g}")
        out.append(f"| {e} ({sum(succ['plain'][e])}/20) | " + " | ".join(cells) + f" | {sum(cs)}/{len(cs)} | "
                   + ", ".join(pv) + " |")

    out += ["", "## 6. How coin-weighing fails (the task the model is best at)", "",
            "| Condition | solved | answered a coin its own weighings ruled out | other failure |", "|---|---|---|---|"]
    for lab in data:
        sol = bad = other = 0
        for ep in data[lab]:
            if ep["env"] != "oddcoin":
                continue
            if ep["success"]:
                sol += 1
            elif "contradicts" in diagnose.classify(ep):
                bad += 1
            else:
                other += 1
        out.append(f"| {lab} | {sol} | {bad} | {other} |")
    Path("ANALYSIS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
