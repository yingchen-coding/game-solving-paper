"""Collect every finished eval run into RESULTS.md: held-out success (Circuit + BugFix), game success,
repeat rate, with 95% bootstrap intervals, and the difference from the plain baseline.

    python results.py
"""
from __future__ import annotations

import json
import random
from pathlib import Path

import evaluate

RUNS = [  # (label, run dir, how it was taught)
    ("Plain", "q7_plain", "baseline"), ("Lecture", "q7_strategy", "baseline"),
    ("Encourage (moment)", "moment_encourage", "in the moment"), ("Yell (moment)", "moment_yell", "in the moment"),
    ("Remind (moment)", "moment_remind", "in the moment"), ("Hint (moment)", "moment_hint", "in the moment"),
    ("Coach (moment)", "moment_coach", "in the moment"),
    ("Practice", "q7_ei_r1", "sticks"), ("Diary (playbook)", "q7_playbook", "sticks"),
    ("Practice + Diary", "q7_ei_playbook", "sticks"), ("Dream", "stick_dream", "sticks"),
    ("Encourage (practice)", "stick_encourage", "sticks"), ("Yell (practice)", "stick_yell", "sticks"),
    ("Remind (practice)", "stick_remind", "sticks"), ("Hint (practice)", "stick_hint", "sticks"),
    ("Coach (practice)", "stick_coach", "sticks"),
    ("Expert playbook (not clean)", "h8_expert", "reference"),
    ("Diary, error-typed", "h_taxonomy", "sticks"), ("Diary, contrastive", "h_contrastive", "sticks"),
]
HELD = ("circuit", "bugfix")
GAMES = ("guessnumber", "codebreak", "hiddenrule", "oddcoin")


def load(run):
    p = Path("runs") / run / "episodes.jsonl"
    return [json.loads(x) for x in p.open()] if p.exists() else []


def rate(rows, envs_):
    xs = [r["success"] for r in rows if r["env"] in envs_]
    return (sum(xs) / len(xs), len(xs)) if xs else (None, 0)


def diff_ci(a, b, envs_, n=2000):
    """Bootstrap 95% CI of success(a) - success(b), resampling episodes within each env."""
    rng = random.Random(0)
    by = lambda rows: {e: [r["success"] for r in rows if r["env"] == e] for e in envs_}
    A, B = by(a), by(b)
    if any(not A[e] or not B[e] for e in envs_):
        return None
    ds = []
    for _ in range(n):
        sa = [rng.choice(A[e]) for e in envs_ for _ in A[e]]
        sb = [rng.choice(B[e]) for e in envs_ for _ in B[e]]
        ds.append(sum(sa) / len(sa) - sum(sb) / len(sb))
    ds.sort()
    return ds[int(0.025 * n)], ds[int(0.975 * n)]


def main():
    base = load("q7_plain")
    lines = ["# Results (generated by results.py — do not edit by hand)", "",
             "Qwen2.5-7B-Instruct 4-bit; eval seeds >= 10000; held-out = Circuit + BugFix (never practised).", "",
             "| Teaching | Tested | Held-out success | Δ vs Plain (95% CI) | Games success | Repeat rate | n |",
             "|---|---|---|---|---|---|---|"]
    for label, run, kind in RUNS:
        rows = load(run)
        if not rows:
            continue
        h, nh = rate(rows, HELD)
        g, _ = rate(rows, GAMES)
        rep = sum(evaluate.repeats(r) for r in rows) / max(1, sum(r["steps"] for r in rows))
        ci = diff_ci(rows, base, HELD) if run != "q7_plain" and base else None
        d = f"{h - rate(base, HELD)[0]:+.2f} [{ci[0]:+.2f}, {ci[1]:+.2f}]" if ci else "—"
        fmt = lambda x: "—" if x is None else f"{x:.2f}"
        lines.append(f"| {label} | {kind} | {fmt(h)} | {d} | {fmt(g)} | {rep:.2f} | {len(rows)} |")
    lines += ["", "Per-env success:", "", "| Run | " + " | ".join(GAMES + HELD) + " |", "|---" * 7 + "|"]
    for label, run, _ in RUNS:
        rows = load(run)
        if rows:
            cells = [rate(rows, (e,)) for e in GAMES + HELD]
            lines.append(f"| {label} | " + " | ".join("—" if v is None else f"{v:.2f} ({k})" for v, k in cells) + " |")
    Path("RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
